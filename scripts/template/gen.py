"""Generate the template's board plumbing from template/boards.toml.

boards.toml is the one place that knows what each board needs. Three
files are derived from it, so that nothing about a board is written down
twice:

- template/cargo-generate.toml: the prompts (which boards, and which of
  them ask 32- or 64-bit).
- template/hooks/board.rhai: the hook that turns the answers into the
  variables the template's files use. cargo-generate's Rhai can't read
  TOML, so the table is written into the hook as a literal.
- template/boards.json: the same resolved table, for the site's project
  selector.

    uv run scripts/template/gen.py           # rewrite the three files
    uv run scripts/template/gen.py --check   # fail if any is stale (CI)
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "template"
HEADER = "GENERATED by scripts/template/gen.py from boards.toml. Do not edit."


def resolve(table: dict) -> dict:
    """Every board x arch, flattened into the variables a project needs."""
    firmware = table["firmware"]
    loader = table["loader"]
    firmware_url = (
        f"https://raw.githubusercontent.com/raspberrypi/firmware/{firmware['ref']}/boot"
    )
    loader_url = loader["url"].format(version=loader["version"])

    boards = []
    for board in table["board"]:
        variants = {}
        for arch in board["arches"]:
            spec = table["arch"][arch]
            loader_image = (
                f"rpi-loader-{loader['version']}-{board['chip']}-{spec['kernel']}"
            )
            if loader_image not in loader["sha256"]:
                sys.exit(
                    f"{board['id']}/{arch}: no checksum for {loader_image} in [loader.sha256]"
                )
            for name in board["firmware"]:
                if name not in firmware["sha256"]:
                    sys.exit(
                        f"{board['id']}: no checksum for {name} in [firmware.sha256]"
                    )

            # What goes on the card, by the name it has there, and its
            # checksum. The loader image is renamed to the bare kernel name.
            card = {name: firmware["sha256"][name] for name in board["firmware"]}
            card["LICENCE.broadcom"] = firmware["sha256"]["LICENCE.broadcom"]
            card[spec["kernel"]] = loader["sha256"][loader_image]

            variants[arch] = {
                "board": board["id"],
                "board_name": board["name"],
                "chip": board["chip"],
                "arch": arch,
                "target": spec["target"],
                "kernel": spec["kernel"],
                "load_addr": spec["load_addr"],
                "nightly": spec["nightly"],
                "config_txt": board["config"][arch],
                "firmware_url": firmware_url,
                "firmware_files": board["firmware"] + ["LICENCE.broadcom"],
                "loader_version": loader["version"],
                "loader_url": loader_url,
                "loader_image": loader_image,
                "card_sha256": card,
            }
        boards.append(
            {
                "id": board["id"],
                "name": board["name"],
                "arches": board["arches"],
                "variants": variants,
            }
        )
    return {"boards": boards}


def toml_str(s: str) -> str:
    return json.dumps(s)


def cargo_generate_toml(resolved: dict) -> str:
    ids = [b["id"] for b in resolved["boards"]]
    two_arch = [b["id"] for b in resolved["boards"] if len(b["arches"]) > 1]
    condition = " || ".join(f'board == "{i}"' for i in two_arch)
    lines = [
        f"# {HEADER}",
        "",
        "[template]",
        'cargo_generate_version = ">=0.21.0"',
        "# The board table and its plumbing describe the template, not the",
        "# project it generates.",
        'ignore = ["boards.toml", "boards.json", "hooks"]',
        "",
        "[placeholders.board]",
        'type = "string"',
        'prompt = "Which board?"',
        f"choices = [{', '.join(toml_str(i) for i in ids)}]",
        f"default = {toml_str(ids[0])}",
        "",
        "# Only boards that can start in either execution state ask; the hook",
        "# fills in the only one a board has.",
        f"[conditional.'{condition}'.placeholders.arch]",
        'type = "string"',
        'prompt = "32-bit or 64-bit?"',
        'choices = ["32", "64"]',
        'default = "32"',
        "",
        "[hooks]",
        'pre = ["hooks/board.rhai"]',
        "",
    ]
    return "\n".join(lines)


def rhai_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        # JSON string escapes are valid Rhai string escapes.
        return json.dumps(v)
    raise TypeError(f"no Rhai literal for {v!r}")


def board_rhai(resolved: dict) -> str:
    out = [
        f"// {HEADER}",
        "//",
        "// Runs after the prompts. Sets the variables the template's files use,",
        "// from the answers: `board`, and `arch` where the board asked.",
        "",
        "let variants = #{",
    ]
    for board in resolved["boards"]:
        for arch, v in board["variants"].items():
            fields = {
                k: v[k]
                for k in (
                    "board_name",
                    "chip",
                    "target",
                    "kernel",
                    "load_addr",
                    "nightly",
                    "config_txt",
                    "firmware_url",
                    "loader_url",
                    "loader_image",
                )
            }
            fields["arch"] = arch
            fields["firmware_files"] = " ".join(v["firmware_files"])
            fields["card_sha256"] = "".join(
                f"{sha}  {name}\n" for name, sha in v["card_sha256"].items()
            )
            body = ", ".join(f"{k}: {rhai_value(val)}" for k, val in fields.items())
            out.append(f'    "{board["id"]}/{arch}": #{{ {body} }},')
    out.append("};")
    out.append("")
    out.append("let defaults = #{")
    for board in resolved["boards"]:
        out.append(f'    "{board["id"]}": {json.dumps(board["arches"][0])},')
    out.append("};")
    out.append(
        """
let board = variable::get("board");
let arch = if variable::is_set("arch") { variable::get("arch") } else { defaults[board] };
let key = board + "/" + arch;
if !(key in variants) {
    throw "no " + arch + " build for " + board;
}
let v = variants[key];
for name in v.keys() {
    variable::set(name, v[name]);
}
"""
    )
    return "\n".join(out)


def boards_json(resolved: dict) -> str:
    return json.dumps({"_comment": HEADER, **resolved}, indent=2) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if a generated file is stale"
    )
    args = parser.parse_args()

    with open(TEMPLATE / "boards.toml", "rb") as f:
        resolved = resolve(tomllib.load(f))

    outputs = {
        TEMPLATE / "cargo-generate.toml": cargo_generate_toml(resolved),
        TEMPLATE / "hooks" / "board.rhai": board_rhai(resolved),
        TEMPLATE / "boards.json": boards_json(resolved),
    }

    stale = []
    for path, content in outputs.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")

    if stale:
        names = ", ".join(str(p) for p in stale)
        sys.exit(
            f"stale: {names}; run `uv run scripts/template/gen.py` and commit the result"
        )


if __name__ == "__main__":
    main()
